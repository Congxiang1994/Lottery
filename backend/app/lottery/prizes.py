"""彩票奖级判定：双色球（6 级）+ 大乐透（9 级）。

官方奖级规则（中国福利彩票 / 中国体育彩票现行规则）：

双色球（红 6/33 + 蓝 1/16）
----
一等 6+1   二等 6+0   三等 5+1   四等 5+0 或 4+1
五等 4+0 或 3+1   六等 2+1 / 1+1 / 0+1（蓝球命中即得）

大乐透（前 5/35 + 后 2/12）
----
一等 5+2   二等 5+1   三等 5+0   四等 4+2   五等 4+1
六等 3+2   七等 4+0   八等 3+1 或 2+2   九等 3+0 或 1+2 或 2+1 或 0+2

判定输入为命中个数（红命中数、蓝命中数），与具体号码无关。
"""
from __future__ import annotations

# (red_hit, blue_hit) -> 奖级名。蓝键 = blue_count 时蓝球全中，键值用命中数表达。
SSQ_LEVELS: dict[tuple[int, int], str] = {
    (6, 1): "一等奖", (6, 0): "二等奖", (5, 1): "三等奖",
    (5, 0): "四等奖", (4, 1): "四等奖",
    (4, 0): "五等奖", (3, 1): "五等奖",
    (2, 1): "六等奖", (1, 1): "六等奖", (0, 1): "六等奖",
}

DLT_LEVELS: dict[tuple[int, int], str] = {
    (5, 2): "一等奖", (5, 1): "二等奖", (5, 0): "三等奖",
    (4, 2): "四等奖", (4, 1): "五等奖", (3, 2): "六等奖",
    (4, 0): "七等奖",
    (3, 1): "八等奖", (2, 2): "八等奖",
    (3, 0): "九等奖", (1, 2): "九等奖", (2, 1): "九等奖", (0, 2): "九等奖",
}

_TABLES = {"ssq": SSQ_LEVELS, "dlt": DLT_LEVELS}


def prize_level(lottery: str, red_hit: int, blue_hit: int) -> str | None:
    """按彩种与命中数返回奖级名（如 "四等奖"），未中奖返回 None。"""
    table = _TABLES.get(lottery)
    if table is None:
        return None
    return table.get((int(red_hit), int(blue_hit)))
