# ---------------------------------------------------------------- 抓取入口（两个）
# 2026-10-29 实测结论 —— 改这里之前先复读：
#
# ① 精选流 `/jingxuan/pN/` = **时间序**，是「发现」的主入口。
#    每页 20 条、翻页有效（p1~p4 完全不重叠）、上架时分严格倒序
#    （p1 首条 09:28 → p4 首条 09:20，20 条/3 分钟 ≈ 6.7 条/分钟），
#    判据 20/20 齐全（值/不值/收藏/评论/价格/cate_level1）。
#    它的存在决定了新好价多久能进库。
#
# ② 首页推荐流 `/` = **算法推荐序**，只抓 1 页。
#    它的 `/pN/` 分页早已失效：p2~p7 每页都返回同一屏（相邻页重叠 13~17 条），
#    以前「每轮 5 页」实际是 5 次请求抓同一批 18 条 —— 4/5 的请求纯属白烧。
#    它的价值不在翻页：能上首页的都是**热度已攒够**的（发现延迟中位 181 分钟），
#    正好兜住精选流窗口外滑掉、但后来被值友顶起来的那批。
#
# 两者互补：精选流管「快」，首页管「全」。
JINGXUAN_PATH = "/jingxuan"
HOME_PATH = "/"

# ---------------------------------------------------------------- 抓取节奏
# 每轮间隔（秒）。10 分钟一轮 → 进库延迟 ≤10 分钟。
# 精选流 6.7 条/分钟，3 页 × 20 条 = 60 条 ≈ 9 分钟的量，10 分钟一轮刚好接得上；
# 20 分钟一轮会漏掉一半（漏的量虽然首页能兜，但兜回来就晚了 3 小时）。
FETCH_INTERVAL_SECONDS = 10 * 60
# 每轮抓几页精选流（每页 20 条）。3 页 ≈ 60 条 ≈ 最近 9 分钟。
PAGES_PER_ROUND = 3
# 每轮抓几页首页推荐流。固定 1 页 —— 分页失效，多抓只是拿同一屏（见上①说明）。
HOME_PAGES_PER_ROUND = 1
# 单个请求最小间隔（秒）。实测 30~40 次/3~4 分钟即触发防水墙，
# 本域每轮 4 次请求、间隔 10 分钟，平均 0.4 次/分钟，瞬时留 3 秒余量足够。
MIN_REQUEST_INTERVAL_SECONDS = 3.0
# 命中验证码后的退避时长（秒）。实测 22 分钟未恢复，取 30 分钟。
BAN_BACKOFF_SECONDS = 30 * 60
# 单请求超时
HTTP_TIMEOUT_SECONDS = 25.0
# 抓取日志保留天数
LOG_KEEP_DAYS = 14
# 好价记录保留天数。
# ⚠️ 2026-10-29 从 30 天降到 7 天：换双入口后日入库量从 ~526 条涨到几千条
# （精选流覆盖站点 ~9600 条/天的大头），30 天会攒到十几万行，而管理页保存阈值
# 要同步 rejudge 全库（10.8ms/522 条线性放大）→ 秒级阻塞。7 天正好对齐前端
# 「7 天」筛选档，够用且不会把保存按钮拖死。
DEALS_KEEP_DAYS = 7

# ---------------------------------------------------------------- 阈值默认值
# 判定式：不属于黑名单品类 且 值率达标 且 下列三项中满足 N 项。
# 为什么不是「评论 > 100 就算热门」：SMZDM 上评论数高经常是因为大家在吵，
# 争议商品不代表「值」。值率是真人投票的直接结果，必须先过关。
#
# 默认值怎么定的（2026-10-29 用线上 517 条真实数据反推，不是拍脑袋）
# -----------------------------------------------------------------
# 原默认 100 / 300 / 100 是按「爆款」想象的，比实际分布高一个数量级：
#   收藏 p90 只有 49，评论 p90 只 18，值 p90 约 90。
# 结果 17.8 小时里只有 7 条能三项取二，一天约 6 条 —— 用户实测「只有 1 条入选」
# （那 1 条还是被品类过滤后才剩的）。按 422 条/天的稳定新增速率折算：
#   85 / 100 / 300 / 100  → 约 6 条/天
#   85 /  50 /  50 /  20  → 约 16 条/天   ← 现在采用
#   85 /  30 /  30 /  10  → 约 21 条/天
# 值率 85% 保持不变：它筛掉的是八成，但样本 ≥5 的条目里有 57 条能过，
# 说明它不是瓶颈；真正过严的一直是那三个绝对数。
