"""什么值得买捡漏域配置：库路径、默认阈值、抓取节奏、限速参数。

设计前提（2026-10-28 实测结论，改动前请先复读）
--------------------------------------------------
1. **列表页就已含全部判据**。首页 `/` 与精选流 `/jingxuan/` 的卡片 HTML 里都有
   值(`price-btn-up`) / 不值(`price-btn-down`) / 收藏(`title="收藏数 N"`)
   / 评论(`title="评论数 N"`) / 价格 / 一级分类 / 卡片标签。
   → 所以**完全不需要抓详情页**（详情页单条 300KB~1MB，列表页一页覆盖 18~20 条）。
   这一条是整个方案能做到「每天 144 次请求」的根本原因。
   ⚠️ 两个入口的分类字段名不同：首页是 `'1级分类'`，精选流是 `'cate_level1'`，
   解析器两套都要认（见 `crawler._RE_CATE1*`）。

2. **裸爬必被风控**。实测 30~40 次请求 / 3~4 分钟即触发腾讯防水墙 TCaptcha，
   IP 级封禁 20 分钟以上未恢复；而同一时刻服务器 IP 完全正常 → 风控按 IP 独立计分。
   → 所以本域自带令牌桶（默认 3 秒/请求）+ 命中即退避，宁可慢也不能被封。

3. **robots.txt 明确 `Disallow: /*?*`**。带查询串的 URL 一律不允许抓。
   → 本域只用纯路径 URL（`/p2/`、`/p3/`…），不碰任何带 `?` 的接口。
"""
