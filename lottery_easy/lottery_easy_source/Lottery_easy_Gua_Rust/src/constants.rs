/// 获取月相信息
pub fn get_moon_phase(lunar_day: i32) -> (&'static str, i32, &'static str) {
    let phase = match lunar_day {
        1 => "朔",
        2..=4 => "蛾眉月",
        5..=7 => "上弦月",
        8..=11 => "盈凸月",
        12..=15 => "望",
        16..=19 => "亏凸月",
        20..=23 => "下弦月",
        _ => "残月",
    };
    
    for &(p, e, d) in MOON_PHASES {
        if p == phase {
            return (p, e, d);
        }
    }
    ("望", 5, "满月，阳气最盛")
}

/// 将值映射到指定范围
pub fn map_to_range(value: i32, min_val: i32, max_val: i32) -> i32 {
    let range_size = max_val - min_val + 1;
    if range_size <= 0 {
        return min_val;
    }
    let result = ((value - min_val) % range_size) + min_val;
    result.max(min_val).min(max_val)
}

