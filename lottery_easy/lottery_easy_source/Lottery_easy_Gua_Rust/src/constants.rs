/// 获取季节（根据农历月份）
pub fn get_season(lunar_month: i32) -> &'static str {
    match lunar_month {
        1 | 2 | 3 => "春",
        4 | 5 | 6 => "夏",
        7 | 8 | 9 => "秋",
        10 | 11 | 12 => "冬",
        _ => "春",
    }
}

